"""Write ``web/src/styles/brand.css`` from ``brand.py``: each int constant as
``--brand-<name>: #RRGGBB;``, so the cards and the web app share one palette (ADR 0004
point 1). ``make brand-css`` runs it; ``--check`` exits 1 when the file is stale.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from those_who_run import brand

OUT = Path(__file__).resolve().parent.parent / "web" / "src" / "styles" / "brand.css"
HEAD = "/* Generated by scripts/brand_css.py from brand.py: run `make brand-css`, never edit. */"


def css() -> str:
    colours = {n: v for n, v in vars(brand).items() if n.isupper() and isinstance(v, int)}
    lines = [
        f"  --brand-{n.lower().replace('_', '-')}: {brand.hex_colour(v)};"
        for n, v in colours.items()
    ]
    return "\n".join([HEAD, ":root {", *lines, "}", ""])


def main(argv: list[str] | None = None, out: Path = OUT) -> int:
    p = argparse.ArgumentParser(description="Write web/src/styles/brand.css from brand.py.")
    p.add_argument("--check", action="store_true", help="fail if the committed file is stale")
    if not p.parse_args(argv).check:
        out.write_text(css(), encoding="utf-8")
        print(f"wrote {out}")
    elif not out.is_file() or out.read_text(encoding="utf-8") != css():
        print(f"{out} is stale: run `make brand-css` and commit it", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
