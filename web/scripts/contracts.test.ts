// The generated client's freshness check (those-who-run/paddock#127 R4): the tag
// it reads, and how two trees are compared.
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it, vi } from "vitest";

import { differences, EXAMPLES, files, goContracts, pinnedTag, pinsDiffer, takeFiles } from "./contracts.ts";

function tree(entries: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), "contracts-test-"));
  for (const [name, body] of Object.entries(entries)) {
    mkdirSync(join(dir, name, ".."), { recursive: true });
    writeFileSync(join(dir, name), body);
  }
  return dir;
}

describe("the contracts check", () => {
  it("reads the tag buf.gen.yaml pins", () => {
    expect(pinnedTag(readFileSync("buf.gen.yaml", "utf8"))).toMatch(/^v\d+\.\d+\.\d+$/);
    expect(pinnedTag("inputs:\n  - git_repo: x\n    tag: v1.2.3\n")).toBe("v1.2.3");
    expect(() => pinnedTag("inputs:\n  - git_repo: x\n    branch: main\n")).toThrow(/pins no contracts tag/);
  });

  it("finds a file added, removed or changed", () => {
    const want = tree({ "a.ts": "1", "b/c.ts": "2", "d.json": "3" });
    expect(files(want)).toEqual(["a.ts", "b/c.ts", "d.json"]);
    expect(differences(want, tree({ "a.ts": "1", "b/c.ts": "2", "d.json": "3" }))).toEqual([]);
    expect(differences(want, tree({ "a.ts": "1", "b/c.ts": "changed", "e.ts": "4" }))).toEqual(["b/c.ts", "d.json", "e.ts"]);
    expect(files(join(want, "missing"))).toEqual([]);
  });

  it("fails when buf.gen.yaml and go.mod pin contracts apart", () => {
    const gomod = "module x\n\nrequire (\n\tgithub.com/those-who-run/contracts v0.2.8\n\tgoogle.golang.org/protobuf v1.36.12\n)\n";
    expect(goContracts(gomod)).toBe("v0.2.8");
    expect(goContracts("module x\n")).toBeNull();
    expect(pinsDiffer("v0.2.8", gomod)).toBeNull();
    expect(pinsDiffer("v0.2.7", gomod)).toMatch(/v0\.2\.7.*v0\.2\.8/);
    expect(pinsDiffer("v0.2.7", "module x\n")).toBeNull();
    // This repository's own pins agree.
    expect(pinsDiffer(pinnedTag(readFileSync("buf.gen.yaml", "utf8")), readFileSync(join("..", "go.mod"), "utf8"))).toBeNull();
  });

  it("the committed client is generated from the pinned tag", () => {
    const gen = files(join("src", "api", "gen"));
    expect(gen).toContain("format-cases.json");
    for (const name of EXAMPLES) {
      expect(gen).toContain(join("examples", name));
    }
    expect(gen).toContain(join("twr", "pitwall", "v1", "pitwall_pb.ts"));
    const tag = pinnedTag(readFileSync("buf.gen.yaml", "utf8"));
    expect(readFileSync(join("src", "api", "gen", "twr", "pitwall", "v1", "pitwall_pb.ts"), "utf8")).toContain("@generated by protoc-gen-es");
    expect(tag).toBeTruthy();
  });

  it("takes the format cases from contracts at the pinned tag, as they are there (#128 R3)", async () => {
    const dir = mkdtempSync(join(tmpdir(), "contracts-test-"));
    const cases = '{"cases":[{"fn":"lapTime","args":[1],"out":"changed"}]}\n';
    const get = vi.fn(async (url: string | URL | Request) =>
      String(url).endsWith("/format/format-cases.json") ? new Response(cases) : new Response("{}"),
    );
    await takeFiles("v9.9.9", dir, get as unknown as typeof fetch);
    const urls = get.mock.calls.map(([u]) => String(u));
    expect(urls).toContain("https://raw.githubusercontent.com/those-who-run/contracts/v9.9.9/format/format-cases.json");
    expect(urls).toHaveLength(1 + EXAMPLES.length);
    expect(readFileSync(join(dir, "format-cases.json"), "utf8")).toBe(cases);
    await expect(takeFiles("v9.9.9", dir, (async () => new Response("", { status: 404 })) as typeof fetch)).rejects.toThrow(
      /GET .*v9\.9\.9\/format\/format-cases\.json: 404/,
    );
  });
});
