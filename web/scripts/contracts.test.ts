// The generated client's freshness check (those-who-run/paddock#127 R4): the tag
// it reads, and how two trees are compared.
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";

import { differences, files, pinnedTag } from "./contracts.ts";

function tree(entries: Record<string, string>): string {
  const dir = mkdtempSync(join(tmpdir(), "contracts-test-"));
  for (const [name, body] of Object.entries(entries)) {
    mkdirSync(join(dir, name, ".."), { recursive: true });
    writeFileSync(join(dir, name), body);
  }
  return dir;
}

describe("the contracts check", () => {
  it("reads the tag buf.gen.yaml pins", () => {
    expect(pinnedTag(readFileSync("buf.gen.yaml", "utf8"))).toMatch(/^v\d+\.\d+\.\d+$/);
    expect(pinnedTag("inputs:\n  - git_repo: x\n    tag: v1.2.3\n")).toBe("v1.2.3");
    expect(() => pinnedTag("inputs:\n  - git_repo: x\n    branch: main\n")).toThrow(/pins no contracts tag/);
  });

  it("finds a file added, removed or changed", () => {
    const want = tree({ "a.ts": "1", "b/c.ts": "2", "d.json": "3" });
    expect(files(want)).toEqual(["a.ts", "b/c.ts", "d.json"]);
    expect(differences(want, tree({ "a.ts": "1", "b/c.ts": "2", "d.json": "3" }))).toEqual([]);
    expect(differences(want, tree({ "a.ts": "1", "b/c.ts": "changed", "e.ts": "4" }))).toEqual(["b/c.ts", "d.json", "e.ts"]);
    expect(files(join(want, "missing"))).toEqual([]);
  });

  it("the committed client is generated from the pinned tag", () => {
    const gen = files(join("src", "api", "gen"));
    expect(gen).toContain("format-cases.json");
    expect(gen).toContain(join("twr", "pitwall", "v1", "pitwall_pb.ts"));
    const tag = pinnedTag(readFileSync("buf.gen.yaml", "utf8"));
    expect(readFileSync(join("src", "api", "gen", "twr", "pitwall", "v1", "pitwall_pb.ts"), "utf8")).toContain("@generated by protoc-gen-es");
    expect(tag).toBeTruthy();
  });
});
